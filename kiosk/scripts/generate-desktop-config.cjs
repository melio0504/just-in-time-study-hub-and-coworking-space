const fs = require("node:fs");
const path = require("node:path");

const { getKioskConfig } = require("../electron/kiosk-api.cjs");

const kioskDirectory = path.join(__dirname, "..");
const environmentFile = path.join(kioskDirectory, ".env.local");
const outputFile = path.join(kioskDirectory, "electron", "build-config.cjs");

if (fs.existsSync(environmentFile)) {
  process.loadEnvFile(environmentFile);
}

const main = () => {
  let config;
  try {
    config = getKioskConfig(process.env);
  } catch (error) {
    const reason = error instanceof Error ? error.message : "Invalid kiosk configuration.";
    console.error(
      `${reason} Add NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, and KIOSK_ACCESS_TOKEN to kiosk/.env.local before launching or packaging Electron.`,
    );
    process.exitCode = 1;
    return;
  }

  const contents =
    `// Generated by scripts/generate-desktop-config.cjs. Do not commit.\n` +
    `"use strict";\n\n` +
    `module.exports = Object.freeze(${JSON.stringify(
      {
        NEXT_PUBLIC_SUPABASE_URL: config.supabaseUrl,
        NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: config.publishableKey,
        KIOSK_ACCESS_TOKEN: config.accessToken,
      },
      null,
      2,
    )});\n`;

  fs.writeFileSync(outputFile, contents, { encoding: "utf8", mode: 0o600 });
  console.log("Embedded kiosk configuration generated for the Electron build.");
};

main();
